"""Rebuild data/brain-slice.js from the full MaleCNS connectome.

Usage:
    python tools/make_slice.py path/to/xenova-reference/dist/data

The input folder is the `dist/data` (or `public/data`) folder of
https://huggingface.co/spaces/Xenova/fruit-fly-simulation, which packs
MaleCNS v1.0 (CC BY 4.0, FlyEM / HHMI Janelia et al.) as gzipped CSR arrays.

Selection:
  outputs  descending "button" neurons (turn L/R, walk, escape)
  middle   top 120 direct inputs to those, plus top 120 two-hop bridges
           from the eye neurons (scored by geometric mean of synapse flow)
  eyes     30 LC4/LPLC2/LC9/LC12 neurons per side with the strongest
           output into the middle layer
The induced subgraph (all real connections among the chosen cells) is kept.
"""
import json, gzip, sys, os
import numpy as np

D = sys.argv[1].rstrip('/\\') + '/' if len(sys.argv) > 1 else 'dist/data/'
OUT_FILE = os.path.join(os.path.dirname(__file__), '..', 'data', 'brain-slice.js')

def arr(name):
    m = json.load(open(D + 'manifest.json'))
    a = [x for x in m['arrays'] if x['name'] == name][0]
    return np.concatenate([np.frombuffer(gzip.open(D + p['file']).read(), dtype=np.uint32) for p in a['parts']])

n = json.loads(gzip.open(D + 'neurons.json.gz').read())
off = arr('offsets')
S = arr('sources').astype(np.int64)
T = np.repeat(np.arange(len(n), dtype=np.int64), np.diff(off))
C = arr('counts').astype(np.float64)
N=len(n); typ=[r[1] for r in n]; side=[r[3] for r in n]; sc=[r[2] for r in n]; sign=np.array([r[5] for r in n])
def idx(types,sd=None): return [i for i in range(N) if typ[i] in types and (sd is None or side[i]==sd)]
OUT={'left':idx(['DNa02','DNa11','DNg13'],'L'),'right':idx(['DNa02','DNa11','DNg13'],'R'),
     'rotate':idx(['DNp09','DNg100','DNg97']),'drop':idx(['DNp01','MDN'])}
INTYPES=['LC9','LC4','LPLC2','LC12']
INL=idx(INTYPES,'L'); INR=idx(INTYPES,'R')
outs=sorted(set(sum(OUT.values(),[]))); ins=INL+INR
print({k:len(v) for k,v in OUT.items()}, len(INL),len(INR))
isout=np.zeros(N,bool); isout[outs]=1; isin=np.zeros(N,bool); isin[ins]=1
# weighted (signed magnitude) flows
w_toO=np.bincount(S[isout[T]],weights=C[isout[T]],minlength=N)
w_fromI=np.bincount(T[isin[S]],weights=C[isin[S]],minlength=N)
mid_ok=np.array([not(isin[i] or isout[i]) and sign[i]!=0 and sc[i] not in('ol_intrinsic',) for i in range(N)])
# level-1: direct presyn of outputs (top 120)
c1=np.where(mid_ok & (w_toO>0))[0]; c1=c1[np.argsort(-w_toO[c1])][:120]
L1=np.zeros(N,bool); L1[c1]=1
w_toL1=np.bincount(S[L1[T]],weights=C[L1[T]],minlength=N)
# level-2: bridges: receive from inputs and project to L1 (top 120 by geometric mean)
sc2=np.sqrt(w_fromI*w_toL1); sc2[~mid_ok]=0; sc2[L1]=0
c2=np.argsort(-sc2)[:120]; c2=c2[sc2[c2]>0]
mids=sorted(set(c1)|set(c2)); M=np.zeros(N,bool); M[mids]=1
# inputs: keep those with strongest output into mids, per side, 30 each
w_inToM=np.bincount(S[M[T]],weights=C[M[T]],minlength=N)
keepL=sorted(INL,key=lambda i:-w_inToM[i])[:30]; keepR=sorted(INR,key=lambda i:-w_inToM[i])[:30]
sel=keepL+keepR+mids+outs; sel=list(dict.fromkeys(sel))
print('sizes',len(keepL),len(keepR),len(mids),len(outs),'total',len(sel))
pos={g:i for i,g in enumerate(sel)}
inset=np.zeros(N,bool); inset[sel]=1
m=inset[S]&inset[T]
es=np.array([pos[x] for x in S[m]]); et=np.array([pos[x] for x in T[m]]); ec=C[m]
print('edges',len(es),'synapses',ec.sum())
role={}
for i in keepL: role[i]='eyeL'
for i in keepR: role[i]='eyeR'
for i in mids: role[i]='mid'
for k,v in OUT.items():
  for i in v: role[i]='out_'+k
neur=[{'id':n[g][0],'type':typ[g],'side':side[g],'nt':n[g][4],'sign':int(sign[g]),'role':role[g],'xyz':n[g][6]} for g in sel]
out={'source':'MaleCNS v1.0 (FlyEM / HHMI Janelia, University of Cambridge, MRC LMB, Google Research), CC BY 4.0 — via Xenova/fruit-fly-simulation preprocessing',
 'note':'Induced subgraph: eye (visual projection) neurons, strongest middle-brain bridges, and descending "button" neurons. Edge weight = synapse count.',
 'neurons':neur,'edges':[[int(a),int(b),int(c)] for a,b,c in zip(es,et,ec)]}

compact = {k: out[k] for k in ('source', 'note')}
NN = out['neurons']
for key in ('id', 'type', 'side', 'nt', 'sign', 'role', 'xyz'):
    compact[key] = [x[key] for x in NN]
compact['edges'] = [v for e in out['edges'] for v in e]
with open(OUT_FILE, 'w') as f:
    f.write('// Generated by tools/make_slice.py — do not edit by hand.\nwindow.BRAIN_SLICE=')
    f.write(json.dumps(compact, separators=(',', ':')))
    f.write(';\n')
print('wrote', OUT_FILE)
